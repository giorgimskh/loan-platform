package ge.kiu.loanplatform.service.document;

import ge.kiu.loanplatform.config.properties.AppProperties;
import ge.kiu.loanplatform.dto.validation.FileValidator;
import ge.kiu.loanplatform.exception.custom.BusinessRuleException;
import ge.kiu.loanplatform.exception.custom.ResourceNotFoundException;
import lombok.RequiredArgsConstructor;
import org.springframework.core.io.FileSystemResource;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.UUID;

// The FileStorageService that keeps files in a folder on this server's disk (app.upload-dir).
// It is the only implementation, so Spring injects it wherever a FileStorageService is asked for.
@Service
@RequiredArgsConstructor
public class LocalFileStorageService implements FileStorageService {

    // the extension the stored file gets, chosen by us from the (already checked) Content-Type
    private static final Map<String, String> EXTENSION_BY_CONTENT_TYPE = Map.of(
            "application/pdf", "pdf",
            "image/jpeg", "jpg",
            "image/png", "png");

    private final AppProperties appProperties;

    // Checks rule 6, saves the file under a new name and returns the path where it was stored
    @Override
    public String store(MultipartFile file) {
        // The same check as @ValidFile on the REST endpoint. It runs here again because the website
        // upload (WebController) calls this service without the annotation: the service is the last line.
        String problem = FileValidator.findProblem(file);
        if (problem != null) {
            throw new BusinessRuleException(problem);
        }

        // The stored name is generated by the server: a random UUID + an extension chosen from the
        // Content-Type. Nothing of the customer's file name is used on disk, so a name like
        // "../../app.properties" or "a/b.pdf" can never choose the folder or overwrite another file,
        // and two uploads called "id.pdf" never collide. The original name is only kept in the database.
        String extension = EXTENSION_BY_CONTENT_TYPE.get(file.getContentType().toLowerCase());
        String storedFileName = UUID.randomUUID() + "." + extension;

        try {
            Path uploadDir = Path.of(appProperties.getUploadDir());
            Files.createDirectories(uploadDir); // does nothing if the folder already exists
            Path target = uploadDir.resolve(storedFileName);
            file.transferTo(target);
            return target.toString();
        } catch (IOException e) {
            throw new UncheckedIOException("Could not store file", e);
        }
    }

    // Opens a stored file for download. Nothing is read here: Spring reads the bytes while it sends the response.
    @Override
    public Resource load(String storedFilePath) {
        Resource resource = new FileSystemResource(storedFilePath);
        if (!resource.exists()) {
            // the database row exists but the file was removed from the uploads folder by hand
            throw new ResourceNotFoundException("The stored file of this document no longer exists");
        }
        return resource;
    }

    @Override
    public void delete(String storedFilePath) {
        try {
            Files.deleteIfExists(Path.of(storedFilePath));
        } catch (IOException e) {
            throw new UncheckedIOException("Could not delete file", e);
        }
    }
}
